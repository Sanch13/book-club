from django.utils import timezone

from .models import Book


def available_years(request):
    """Годы, за которые есть книги, и год по умолчанию — для шапки.

    Шапка рендерится на каждой странице, поэтому годы проще отдать
    через контекстный процессор, чем прокидывать из каждого вьюха.

    nav_year — год, который в выпадающем списке отмечен галочкой.
    По умолчанию текущий календарный год: страницы книги, кабинета и
    рейтинга свой год не передают, и без значения по умолчанию галочка
    не стояла бы нигде. Именно число, а не строка: {% if y == nav_year %}
    сравнивает значения, а «2026» != 2026.
    """
    return {
        'available_years': list(
            Book.objects.order_by('-year').values_list('year', flat=True).distinct()
        ),
        'nav_year': timezone.now().year,
    }
